def write_synthetic_ledger_workbook(path: Path, month: str) -> None:
    """按真实源结构写一个合成"总账对账YYYYMM.xlsx"（openpyxl，整数元，无公式）。"""

    workbook = Workbook()
    sheet = workbook.active
    sheet.title = LEDGER_SHEET
    span_start, span_end = MONTH_SPANS[month]
    sheet.cell(
        row=PERIOD_BANNER_ROW,
        column=1,
        value=f"会计期间： {span_start}--{span_end} 币种： CNX",
    )
    for column, header in enumerate(LEDGER_HEADERS, start=1):
        sheet.cell(row=HEADER_ROW, column=column, value=header)
    for offset, (code, name, endings) in enumerate(SYNTHETIC_ACCOUNTS):
        row = FIRST_DATA_ROW + offset
        ending = endings[month]
        previous_month = _PREVIOUS_MONTH[month]
        # 期初 = 上月期末（1 月开账为 0）；当期发生额记入借或贷一侧，
        # 保证总账恒等式 期末 = 期初 + 借 - 贷 成立。
        opening = endings[previous_month] if previous_month else 0
        flow = abs(ending - opening)
        debit = flow if ending >= 0 else 0
        credit = flow if ending < 0 else 0
        sheet.cell(row=row, column=1, value=code)
        sheet.cell(row=row, column=2, value=name)
        sheet.cell(row=row, column=3, value="CNX")
        sheet.cell(row=row, column=4, value=opening)
        sheet.cell(row=row, column=5, value=debit)
        sheet.cell(row=row, column=6, value=credit)
        sheet.cell(row=row, column=7, value=ending)
    workbook.save(path)


def write_synthetic_ledger_source_dir(target_dir: Path) -> Path:
    """在 target_dir 下生成 202501/202502/202503 三个月的合成总账工作簿。"""

    target_dir.mkdir(parents=True, exist_ok=True)
    for month in SYNTHETIC_MONTHS:
        write_synthetic_ledger_workbook(target_dir / f"总账对账{month}.xlsx", month)
    return target_dir
